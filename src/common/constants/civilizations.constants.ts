const BY_VALUE: ReadonlyMap<StoryCivilization, CivilizationDefinition> =
  new Map(CIVILIZATIONS.map((c) => [c.value, c]));

export function getCivilization(
  value: StoryCivilization | null | undefined,
): CivilizationDefinition | null {
  if (value === null || value === undefined) return null;
  return BY_VALUE.get(value) ?? null;
}

export function getCivilizationLabel(
  value: StoryCivilization | null | undefined,
): string | null {
  const def = getCivilization(value);
  if (!def) return null;
  if (def.kind === 'custom' && def.value !== StoryCivilization.CUSTOM) {
    return def.label;
  }
  return def.value === StoryCivilization.CUSTOM ? 'Custom' : def.label;
}

export function isCustomCivilization(
  value: StoryCivilization | null | undefined,
): boolean {
  return getCivilization(value)?.kind === 'custom';
}

export function getCivilizationsByRegion(
  region: CivilizationRegion,
): readonly CivilizationDefinition[] {
  return CIVILIZATIONS.filter((c) => c.region === region);
}
