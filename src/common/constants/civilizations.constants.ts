import { StoryCivilization } from '../enums/story-civilization.enum';

/**
 * Central, data-driven registry for civilizations.
 *
 * RULES (see requirements):
 * - LANGUAGE is NOT a civilization. Language controls only visible written
 *   text; civilization controls the visual/cultural identity of the world.
 * - The backend stores stable enum values; the frontend receives human-readable
 *   labels via GET /stories/meta/civilizations.
 * - Unspecified relies on story content, location, era/year and theme.
 * - Custom (generic or regional) uses the user's customCivilization value.
 */
export type CivilizationRegion =
  | 'Unspecified'
  | 'Africa'
  | 'Middle East & Ancient Near East'
  | 'Mediterranean & Classical'
  | 'Europe'
  | 'South Asia'
  | 'East Asia'
  | 'Southeast Asia'
  | 'Central Asia'
  | 'North America'
  | 'Mesoamerica'
  | 'South America'
  | 'Oceania'
  | 'Religious-Historical'
  | 'Modern Regional'
  | 'Fantasy'
  | 'Other'
  | 'Custom';

export type CivilizationKind = 'specific' | 'other' | 'custom' | 'unspecified';

export interface CivilizationDefinition {
  value: StoryCivilization;
  label: string;
  region: CivilizationRegion;
  kind: CivilizationKind;
}

